// Uses an externally installed Playwright package; never installs a browser or a model.
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.COMMONS_PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.COMMONS_DEMO_ORIGIN || 'http://127.0.0.1:4319';
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin)) throw new Error('Use a loopback demonstration origin.');
const output = resolve(process.env.COMMONS_BROWSER_OUTPUT || '/private/tmp/commons-demo-browser');
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const index = await (await context.request.get(`${origin}/api/v1/demonstrations`)).json();
  const fixture = index.runs.find(run => run.fixtureMode && run.reviewed);
  assert.ok(fixture, "Start demo:serve to create the scripted fixture first.");
  await page.goto(`${origin}/demonstration?run=${fixture.id}`);
  await page.getByRole('heading', { name: 'One result. Every step inspectable.' }).waitFor();
  await page.getByText('Scripted fixture accounts.', { exact: true }).waitFor();
  await page.getByText('338,350', { exact: true }).first().waitFor();
  assert.equal(await page.locator('body').evaluate(el => el.scrollWidth > innerWidth), false);
  await page.screenshot({ path: `${output}/desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('body').evaluate(el => el.scrollWidth > innerWidth), false);
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: true });
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  assert.equal(await page.locator('html').evaluate(el => el.classList.contains('dark')), true);
  await page.screenshot({ path: `${output}/mobile-dark.png`, fullPage: true });
  await page.getByRole('button', { name: 'Switch to light mode' }).click();
  await page.setViewportSize({ width: 1440, height: 1050 });
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Evidence', exact: true }).click();
  assert.match((await download).suggestedFilename(), /^commons-demo-.*\.json$/);
  await page.getByRole('button', { name: 'Start a public run' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox').first().fill(`browser-${randomUUID().slice(0, 8)}`);
  await dialog.locator('input[type=password]').fill(randomUUID());
  await dialog.getByRole('button', { name: 'Create account', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByText(/^@browser-/).waitFor();
  await page.getByRole('button', { name: 'Start a public run' }).click();
  await page.getByText('No evidence saved yet. An idle notebook is shown honestly.').first().waitFor();
  assert.equal(await page.getByText('Scripted fixture accounts.', { exact: true }).count(), 0);
  assert.equal(await page.getByText('338,350', { exact: true }).count(), 0);
  const registration = await context.request.post(`${origin}/api/agents`, { data: { name: 'Browser fixture worker', framework: 'Browser smoke test' } });
  assert.equal(registration.status(), 201);
  const { agent } = await registration.json();
  await page.reload();
  await page.getByLabel('Your agent', { exact: true }).selectOption(agent.id);
  await page.getByLabel('Private owner instructions').fill('PRIVATE_BROWSER_CANARY_Only perform this public finite exercise.');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Publish grant', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Grant published.' }).waitFor();
  await page.getByText('Your private instruction history', { exact: true }).click();
  await page.getByText('Revision 1 · worker', { exact: true }).waitFor();
  await page.getByRole('checkbox').uncheck();
  // Emergency pause must work without renewed publication consent.
  await page.getByRole('button', { name: 'Pause agent and release work' }).click();
  await page.getByRole('status').filter({ hasText: 'Agent paused.' }).waitFor();
  const runId = new URL(page.url()).searchParams.get('run');
  const publicRun = await (await context.request.get(`${origin}/api/v1/demonstrations/${runId}`)).text();
  assert.equal(publicRun.includes('PRIVATE_BROWSER_CANARY'), false);
  assert.equal(JSON.parse(publicRun).participants[0].paused, true);
  await context.request.post(`${origin}/api/auth/logout`, { data: {} });
  await page.reload();
  await page.getByRole('button', { name: 'Join or sign in', exact: true }).waitFor();
  assert.equal((await page.locator('body').innerText()).includes('PRIVATE_BROWSER_CANARY'), false);
  await page.goto(origin);
  await page.getByRole('link', { name: 'Demonstration', exact: true }).click();
  await page.getByRole('heading', { name: 'One result. Every step inspectable.' }).waitFor();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, checks: ['desktop/mobile layout', 'dark mode', 'evidence export', 'signup', 'new empty run', 'private grant/history', 'pause without consent', 'public canary exclusion', 'logout privacy', 'home navigation'], output }));
} finally { await browser.close(); }
